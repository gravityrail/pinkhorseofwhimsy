export const FONT_H = 7;
const CW = 5, GAP = 1;

export function textWidth(str, scale = 1) {
  return str.length * (CW + GAP) * scale - GAP * scale;
}

// Draw text with lit pixels as fillRect. color is a CSS color string.
export function drawText(ctx, str, x, y, scale, color) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const s = scale;
  for (let n = 0; n < str.length; n++) {
    const g = G[str[n]] || G['?'];
    for (let row = 0; row < 7; row++) {
      const line = g[row];
      for (let col = 0; col < 5; col++) {
        if (line[col] === '#') ctx.fillRect(cx + col * s, Math.round(y) + row * s, s, s);
      }
    }
    cx += (CW + GAP) * s;
  }
}

// same but with a 1px drop-shadow/outline for readability on busy backgrounds.
export function drawTextShadow(ctx, str, x, y, scale, color, shadow = '#151221') {
  drawText(ctx, str, x + scale, y + scale, scale, shadow);
  drawText(ctx, str, x, y, scale, color);
}

export function drawTextCentered(ctx, str, cx, y, scale, color, shadow) {
  const x = Math.round(cx - textWidth(str, scale) / 2);
  if (shadow) drawTextShadow(ctx, str, x, y, scale, color, shadow);
  else drawText(ctx, str, x, y, scale, color);
}
